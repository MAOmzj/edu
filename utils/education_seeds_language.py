def build_seeds() -> list[dict]:
    """Return 500 train, 50 validation and 50 test prompts, without final answers."""
    records: list[dict] = []
    for subject, families in (("语文", _chinese_families()), ("英语", _english_families())):
        by_grade = {grade: [family for family in families if family["grade"] == grade] for grade in range(1, 7)}
        if any(len(group) != 10 for group in by_grade.values()):
            raise ValueError(f"{subject}: each grade must contain ten families")
        # 先交错年级，再按任务族划分；训练、验证、测试均覆盖多个年级。
        ordered = [by_grade[grade][slot] for slot in range(10) for grade in range(1, 7)]
        prefix = "zh" if subject == "语文" else "en"
        for family_index, family in enumerate(ordered):
            split = "train" if family_index < 50 else "validation" if family_index < 55 else "test"
            group_id = f"education_{prefix}_g{family['grade']}_{family['code']}"
            for variant, prompt in enumerate(family["prompts"], 1):
                messages = [dict(message) for message in family.get("history", ())]
                messages.append({"role": "user", "content": prompt})
                records.append({
                    "id": f"{group_id}_v{variant:02d}",
                    "group_id": group_id,
                    "subject": subject,
                    "grade": family["grade"],
                    "skill": family["skill"],
                    "split": split,
                    "messages": messages,
                    "source": "synthetic_authored",
                    "quality_checks": {
                        "grounding": "仅使用题面材料；把推测、假设、计划与事实区分开",
                        "teaching": "按年级解释并给具体帮助；已有正确表达无需强行修改",
                        "accuracy": "语文字词与英语拼写、语法、时态、指代应准确",
                    },
                })
    return records


