def _family(key, grade, skill, questions, facts="", history=None):
    questions = questions.split("|")
    if len(questions) != 5:
        raise ValueError(f"任务族{key}必须有5个变体")
    checks = facts.split("|") if facts else []
    if checks and len(checks) not in {1, 5}:
        raise ValueError(f"任务族{key}的核验提示必须为1或5项")
    return {"key": key, "grade": grade, "skill": skill, "questions": questions,
            "checks": checks, "history": history}


