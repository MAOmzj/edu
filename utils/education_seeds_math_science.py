def build_seeds():
    """返回600条输入，数学/科学各300；没有教师答案或训练target。"""
    records = []
    for subject, prefix, families in [
        ("数学", "math", _math_families()), ("科学", "science", _science_families()),
    ]:
        if len(families) != 60:
            raise ValueError(f"{subject}需要60族，实际{len(families)}")
        for index, family in enumerate(families):
            split = "train" if index < 50 else "validation" if index < 55 else "test"
            group = f"edu-{prefix}-{family['key']}"
            for variant, question in enumerate(family["questions"], 1):
                messages = []
                if family["history"]:
                    user, assistant = family["history"]
                    messages.extend([{"role": "user", "content": user},
                                     {"role": "assistant", "content": assistant}])
                messages.append({"role": "user", "content": question})
                facts = family["checks"]
                records.append({
                    "id": f"{group}-v{variant}", "group_id": group,
                    "canonical_task": f"{prefix}:{family['key']}",
                    "source": "synthetic_authored", "subject": subject,
                    "grade": family["grade"], "skill": family["skill"], "split": split,
                    "messages": messages,
                    "quality_checks": {
                        "facts": [facts[variant - 1]] if len(facts) == 5 else list(facts),
                        "focus": family["skill"],
                        "note": "仅供独立核验，不可加入教师模型提示或训练消息；不是教师答案",
                    },
                })
    return records
