def build_seeds():
    """只在原有科学训练任务族内增加375条输入，保持验证和测试族隔离。"""
    original = [r for r in _original_seeds() if r["subject"] == "科学"]
    bases = {r["group_id"]: r for r in original if r["split"] == "train"}
    heldout_groups = {r["group_id"] for r in original if r["split"] != "train"}
    groups = sorted(bases)
    scenarios = _scenarios()
    if len(groups) != 50 or set(groups) & heldout_groups:
        raise ValueError("原科学训练任务族数量或分割发生变化，请重新检查扩充设计")
    if {g.removeprefix("edu-science-") for g in groups} != set(scenarios):
        raise ValueError("科学扩充情境必须与原50个训练任务族一一对应")
    result = []
    for group_index, group_id in enumerate(groups):
        base = bases[group_id]
        family = group_id.removeprefix("edu-science-")
        pack = scenarios[family]
        count = 8 if group_index < 25 else 7
        if len(pack["questions"]) != count:
            raise ValueError(f"{family}需要{count}个新题面")
        for variant, question in enumerate(pack["questions"], 1):
            messages = []
            if variant <= 2:
                user, assistant = pack["history"]
                messages.extend([
                    {"role": "user", "content": user},
                    {"role": "assistant", "content": assistant},
                ])
            messages.append({"role": "user", "content": question})
            result.append({
                "id": f"edu-extra-science-{family}-v{variant:02d}",
                "group_id": group_id,
                "subject": "科学",
                "grade": base["grade"],
                "skill": base["skill"],
                "split": "train",
                "source": "synthetic_authored",
                "messages": messages,
                "quality_checks": {
                    "facts": list(base["quality_checks"]["facts"]) + [pack["notes"]],
                    "focus": base["skill"],
                    "note": "仅供独立核验，不得加入教师提示或训练消息；不是教师目标答案",
                },
            })
    if len(result) != 375:
        raise ValueError("科学新增输入条数必须为375")
    return result
