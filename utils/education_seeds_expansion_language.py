def build_seeds() -> list[dict]:
    """Build 750 additional train inputs, preserving the old split boundaries."""
    old = _original_seeds()
    groups: dict[str, dict] = {}
    for record in old:
        if record["split"] == "train":
            groups.setdefault(record["group_id"], record)
    result = []
    for subject, prefix, builder in (("语文", "zh", _zh), ("英语", "en", _en)):
        ordered = sorted((group_id, seed) for group_id, seed in groups.items() if seed["subject"] == subject)
        if len(ordered) != 50:
            raise ValueError(f"{subject}: expected 50 original train families")
        for group_index, (group_id, seed) in enumerate(ordered):
            family = group_id.removeprefix(f"education_{prefix}_")
            code = family.split("_", 1)[1]
            for variant in range(8 if group_index < 25 else 7):
                prompt, facts, history = builder(code, variant)
                messages = []
                if history:
                    question, answer = history
                    messages.extend(({"role": "user", "content": question}, {"role": "assistant", "content": answer}))
                messages.append({"role": "user", "content": prompt})
                result.append({
                    "id": f"edu-extra-{prefix}-{family}-v{variant + 1:02d}",
                    "group_id": group_id,
                    "subject": subject,
                    "grade": seed["grade"],
                    "skill": seed["skill"],
                    "split": "train",
                    "source": "synthetic_authored",
                    "messages": messages,
                    "quality_checks": {
                        "facts": facts,
                        "grounding": "区分题面明确事实、合理推测、创作示范和缺少的信息；不编造补齐",
                        "teaching": "按年级直接讲解；保留正确表达；礼貌纠错；有先后指令时先执行所要求的步骤",
                    },
                })
    _validate(result, old)
    return result


def _validate(records: list[dict], old: list[dict]) -> None:
    if Counter(record["subject"] for record in records) != {"语文": 375, "英语": 375}:
        raise ValueError("additional language dataset must contain 375 records per subject")
    if len({record["id"] for record in records}) != 750:
        raise ValueError("duplicate additional seed id")
    prompts = [json.dumps(record["messages"], ensure_ascii=False, sort_keys=True) for record in records]
    if len(set(prompts)) != 750:
        raise ValueError("duplicate additional conversation")
    old_prompts = {json.dumps(record["messages"], ensure_ascii=False, sort_keys=True) for record in old}
    old_last = {record["messages"][-1]["content"] for record in old}
    if set(prompts) & old_prompts or any(record["messages"][-1]["content"] in old_last for record in records):
        raise ValueError("additional task duplicates an original question")
    old_groups = {record["group_id"] for record in old if record["split"] == "train"}
    held_out = {record["group_id"] for record in old if record["split"] != "train"}
    if {record["group_id"] for record in records} != old_groups or old_groups & held_out:
        raise ValueError("additional data must reuse only original train groups")
    if sum(len(record["messages"]) > 1 for record in records) < 113:
        raise ValueError("additional data requires at least 15 percent meaningful follow-up conversations")
    for record in records:
        if record["split"] != "train" or [message["role"] for message in record["messages"]] not in (["user"], ["user", "assistant", "user"]):
            raise ValueError("invalid split or conversation roles")
        if any(not message["content"].strip() for message in record["messages"]):
            raise ValueError("empty message")


