    for index, (group_id, base) in enumerate(sorted(families.items())):
        family = group_id.removeprefix("edu-math-")
        rule, questions = _TASKS[family]
        count = 8 if index < 25 else 7
        if len(questions) != count:
            raise ValueError(f"{family}需要{count}题，实际{len(questions)}")
        for variant, (question, facts) in enumerate(questions, 1):
            messages = []
            if variant in {2, 6}:
                messages.extend([
                    {"role": "user", "content": f"我想复习{base['skill']}，请先说一个基本规则。"},
                    {"role": "assistant", "content": rule},
                ])
            messages.append({"role": "user", "content": question})
            records.append({
                "id": f"edu-extra-math-{family}-v{variant:02d}",
                "group_id": group_id,
                "canonical_task": base.get("canonical_task", f"math:{family}"),
                "source": "synthetic_authored",
                "subject": "数学",
                "grade": base["grade"],
                "skill": base["skill"],
                "split": "train",
                "messages": messages,
                "quality_checks": {
                    "facts": [facts],
                    "focus": base["skill"],
                    "note": "仅供独立核验；禁止加入教师模型提示或训练消息；不是最终教师答案。",
                },
            })
    if len(records) != 375:
        raise ValueError(f"数学扩充应有375条，实际{len(records)}")
    return records
